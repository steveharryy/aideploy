import type {
  AIProvider,
  AIProviderGenerateOptions,
  AIProviderResponse,
  FileChange
} from '../models/types.js';

export interface ClaudeProviderConfig {
  apiKey?: string;
  model?: string;
  apiUrl?: string;
  maxTokens?: number;
}

/**
 * ClaudeProvider
 *
 * Implements AIProvider for Anthropic's Claude models.
 * Sends structured context to Claude and receives file change specifications.
 */
export class ClaudeProvider implements AIProvider {
  public readonly name = 'claude';
  private apiKey: string;
  private model: string;
  private apiUrl: string;
  private maxTokens: number;

  constructor(config: ClaudeProviderConfig = {}) {
    this.apiKey = config.apiKey || process.env.ANTHROPIC_API_KEY || '';
    this.model = config.model || process.env.ANTHROPIC_MODEL || 'claude-3-5-sonnet-20241022';
    this.apiUrl = config.apiUrl || 'https://api.anthropic.com/v1/messages';
    this.maxTokens = config.maxTokens || 4096;
  }

  async generateChanges(options: AIProviderGenerateOptions): Promise<AIProviderResponse> {
    if (!this.apiKey) {
      throw new Error(
        'ClaudeProvider Error: Missing ANTHROPIC_API_KEY. ' +
        'Please set the ANTHROPIC_API_KEY environment variable or select AI_PROVIDER=mock.'
      );
    }

    const { task, repoContext, systemPrompt } = options;

    const defaultSystemPrompt =
      'You are an expert software engineer operating as a Repo Agent in an AI Orchestration system. ' +
      'Your task is to analyze existing files in a repository and implement the requested changes. ' +
      'You must return ONLY a JSON object with this exact shape:\n' +
      '{\n' +
      '  "reasoning": "brief explanation of what you changed and why",\n' +
      '  "fileChanges": [\n' +
      '    {\n' +
      '      "path": "path/relative/to/repo/root.ts",\n' +
      '      "action": "create" | "modify" | "delete",\n' +
      '      "content": "full content of the file"\n' +
      '    }\n' +
      '  ]\n' +
      '}\n' +
      'Do not include markdown conversational filler outside the JSON.';

    const fileSnapshotsSummary = repoContext.existingFiles
      .map((f) => `--- File: ${f.path} ---\n${f.content}\n--- End of File ---`)
      .join('\n\n');

    const userPrompt = `Repository: ${repoContext.repoId}

Task ID: ${task.id}
Title: ${task.title}
Description: ${task.description}
Acceptance Criteria:
${task.acceptanceCriteria.map((c, i) => `  ${i + 1}. ${c}`).join('\n')}

Existing Repository Files:
${fileSnapshotsSummary || '(Repository is currently empty)'}

Generate the exact file changes to satisfy the task and acceptance criteria. Return ONLY JSON.`;

    const requestBody = {
      model: this.model,
      max_tokens: this.maxTokens,
      system: systemPrompt || defaultSystemPrompt,
      messages: [
        {
          role: 'user',
          content: userPrompt
        }
      ]
    };

    const response = await fetch(this.apiUrl, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': this.apiKey,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify(requestBody)
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Claude API request failed with status ${response.status}: ${errorText}`);
    }

    const data = (await response.json()) as {
      content?: Array<{ type: string; text?: string }>;
    };

    const textContent =
      data.content?.find((c) => c.type === 'text')?.text || '';

    // Parse the JSON response
    const parsed = this.parseClaudeResponse(textContent);

    return {
      providerName: this.name,
      reasoning: parsed.reasoning || 'Changes generated by Claude.',
      fileChanges: parsed.fileChanges || [],
      rawResponse: textContent
    };
  }

  private parseClaudeResponse(text: string): { reasoning: string; fileChanges: FileChange[] } {
    let cleanJson = text.trim();

    // Remove markdown code block fences if present (```json ... ```)
    const jsonFenceMatch = cleanJson.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
    if (jsonFenceMatch) {
      cleanJson = jsonFenceMatch[1].trim();
    }

    try {
      const parsed = JSON.parse(cleanJson);
      if (Array.isArray(parsed.fileChanges)) {
        return parsed;
      }
      throw new Error('Parsed response does not contain a fileChanges array');
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : String(err);
      throw new Error(`Failed to parse Claude response into structured file changes: ${message}\nRaw text: ${text}`);
    }
  }
}
